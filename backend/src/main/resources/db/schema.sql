-- Esquema de la base de datos (H2). Idempotente: se ejecuta en cada arranque.
-- Los instantes se guardan como TIMESTAMP WITH TIME ZONE en UTC.

CREATE TABLE IF NOT EXISTS person (
    id           VARCHAR(32) PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    team         VARCHAR(40)
);

-- La definicion depende del tipo (CONTINUOUS, SPLIT, ROTATING_SHIFT, ON_CALL) y se guarda en JSON.
CREATE TABLE IF NOT EXISTS schedule (
    id                VARCHAR(64) PRIMARY KEY,
    name              VARCHAR(80) NOT NULL,
    kind              VARCHAR(20) NOT NULL,
    tolerance_minutes INT         NOT NULL,
    definition        CLOB        NOT NULL
);

CREATE TABLE IF NOT EXISTS schedule_assignment (
    id          VARCHAR(64) PRIMARY KEY,
    schedule_id VARCHAR(64) NOT NULL REFERENCES schedule (id),
    target_type VARCHAR(10) NOT NULL,
    target_id   VARCHAR(40) NOT NULL,
    valid_from  DATE        NOT NULL,
    valid_to    DATE,
    CONSTRAINT assignment_period CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE IF NOT EXISTS holiday (
    holiday_date DATE PRIMARY KEY,
    description  VARCHAR(80) NOT NULL
);

-- Registro de fichajes de solo anadir (la aplicacion no actualiza ni borra filas).
CREATE TABLE IF NOT EXISTS clock_event (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          VARCHAR(64) PRIMARY KEY,
    person_id   VARCHAR(32) NOT NULL REFERENCES person (id),
    event_type  VARCHAR(10) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    source      VARCHAR(10) NOT NULL,
    note        VARCHAR(200)
);
CREATE INDEX IF NOT EXISTS idx_clock_event_person_time ON clock_event (person_id, occurred_at);

CREATE TABLE IF NOT EXISTS incident_justification (
    incident_key VARCHAR(160) PRIMARY KEY,
    person_id    VARCHAR(32)  NOT NULL REFERENCES person (id),
    reason       VARCHAR(200) NOT NULL,
    justified_by VARCHAR(40)  NOT NULL,
    justified_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Auditoria de todas las modificaciones (altas, horarios, asignaciones, fichajes, justificaciones).
CREATE TABLE IF NOT EXISTS audit_log (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logged_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    actor       VARCHAR(40)  NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(30)  NOT NULL,
    entity_id   VARCHAR(160) NOT NULL,
    detail      VARCHAR(400)
);

-- Centros de trabajo (edificios, tiendas, plantas...).
CREATE TABLE IF NOT EXISTS workplace (
    id      VARCHAR(32) PRIMARY KEY,
    name    VARCHAR(80) NOT NULL,
    address VARCHAR(120)
);
ALTER TABLE schedule_assignment ADD COLUMN IF NOT EXISTS workplace_id VARCHAR(32) REFERENCES workplace (id);
ALTER TABLE clock_event ADD COLUMN IF NOT EXISTS workplace_id VARCHAR(32) REFERENCES workplace (id);

-- Cuentas de acceso. La clave solo se guarda protegida (PBKDF2 con sal aleatoria).
CREATE TABLE IF NOT EXISTS user_account (
    username      VARCHAR(32)  PRIMARY KEY,
    role          VARCHAR(10)  NOT NULL,
    person_id     VARCHAR(32)  REFERENCES person (id),
    password_hash VARCHAR(300) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
